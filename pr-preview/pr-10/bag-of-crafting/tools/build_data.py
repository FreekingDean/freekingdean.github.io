#!/usr/bin/env python3
"""Build the Bag of Crafting data files from the game's own XML resources.

Usage:
    python3 build_data.py <resources-dir> <stringtable.sta> <version-key> <label> > ../data/<version-key>.js

<resources-dir> holds itempools.xml, items.xml, items_metadata.xml and recipes.xml
exactly as the game ships them (extract with the game's ResourceExtractor).

Sources used for the committed data files:
  repplus  Repentance+ v1.9.7.15  github.com/Derugon/TBoIR-resources (branch 1.9.7.15.J374, resources/)
  rep      Repentance  v1.7.9b    github.com/EliteMasterEric/isaac-crafting (gamedata/pc/v1.7.9b)
"""
import json
import sys
import xml.etree.ElementTree as ET

# Pools the bag can draw from, as indexes into itempools.xml (game ItemPoolType ids).
BAG_POOLS = [0, 1, 2, 3, 4, 5, 7, 8, 9, 12, 26]
# recipes.xml letters, in pickup-id order 1..30 (from the game binary).
RECIPE_CHARS = "hsbegBr.oOQ/|%v^V123[(>?~${4_X"
TAGS = ["offensive", "nogreed", "nokeeper", "nolostbr", "nochallenge"]


def read_xml(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        text = f.read()
    # Some files carry stray bytes/BOM before the root element.
    return ET.fromstring(text[text.index("<"):])


def english_strings(sta_path):
    root = read_xml(sta_path)
    out = {}
    for key in root.iter("key"):
        s = key.find("string")
        if s is not None and s.text:
            out.setdefault(key.get("name"), s.text)
    return out


def main():
    res, sta, key, label = sys.argv[1:5]
    strings = english_strings(sta)

    items = {}
    for el in read_xml(f"{res}/items.xml"):
        if el.tag not in ("passive", "active", "familiar"):
            continue
        name = el.get("name", "")
        if name.startswith("#"):
            name = strings.get(name[1:], name[1:].replace("_NAME", "").replace("_", " ").title())
        items[int(el.get("id"))] = {
            "n": name,
            "a": 1 if el.get("achievement") else 0,
            "act": 1 if el.tag == "active" else 0,
        }

    for el in read_xml(f"{res}/items_metadata.xml"):
        if el.tag != "item":
            continue
        i = int(el.get("id"))
        if i not in items:
            continue
        q = int(el.get("quality", "0"))
        cq = el.get("craftquality")
        items[i]["q"] = q
        items[i]["cq"] = int(cq) if cq is not None else q
        tags = (el.get("tags") or "").split()
        items[i]["t"] = [t for t in TAGS if t in tags]

    pools_root = read_xml(f"{res}/itempools.xml")
    all_pools = [p for p in pools_root if p.tag == "Pool"]
    pools = {}
    for pid in BAG_POOLS:
        p = all_pools[pid]
        pools[pid] = {
            "name": p.get("Name"),
            "items": [[int(i.get("Id")), float(i.get("Weight", "1"))] for i in p if i.tag == "Item"],
        }

    recipes = {}
    for r in read_xml(f"{res}/recipes.xml"):
        if r.tag != "recipe":
            continue
        comps = sorted(RECIPE_CHARS.index(c) + 1 for c in r.get("input"))
        recipes[",".join(map(str, comps))] = int(r.get("output"))

    data = {
        "key": key,
        "label": label,
        "maxItemId": max(items),
        "items": items,
        "pools": pools,
        "recipes": recipes,
    }
    sys.stdout.write("/* Generated by tools/build_data.py from the game's XML. Do not edit by hand. */\n")
    sys.stdout.write(f"(globalThis.BOC_DATA = globalThis.BOC_DATA || {{}})[{json.dumps(key)}] = ")
    sys.stdout.write(json.dumps(data, separators=(",", ":"), ensure_ascii=False))
    sys.stdout.write(";\n")


if __name__ == "__main__":
    main()
